#!/usr/bin/env python3
"""Write sw.js: the list of every file the app needs offline, plus a version from their contents.

Run after tools/sync.py or any change:  python3 tools/build.py
"""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {".git", ".github", "tools", "bilder"}
SKIP_FILES = {"sw.js", "README.md", ".gitignore", ".nojekyll"}

files, digest = [], hashlib.sha256()
for path in sorted(ROOT.rglob("*")):
    rel = path.relative_to(ROOT)
    if path.is_dir() or rel.parts[0] in SKIP_DIRS or rel.name in SKIP_FILES or rel.suffix in (".map", ".d.ts", ".md", ".txt"):
        continue
    files.append(rel.as_posix())
    digest.update(rel.as_posix().encode() + path.read_bytes())
version = digest.hexdigest()[:12]
# Pages are opened as "games/x/", not "games/x/index.html": store both addresses.
dirs = [f[: -len("index.html")] for f in files if f.endswith("/index.html")]
files = ["./"] + [f for f in files if f != "index.html"] + dirs + ["index.html"]

(ROOT / "sw.js").write_text(f"""/* Spieleabend offline – service worker (generated by tools/build.py, do not edit).
 * Stores every file of the app on the device, so it starts without internet. */
const VERSION = "{version}";
const CACHE = "spo-" + VERSION;
const FILES = {json.dumps(files, indent=0)};

async function fill(report) {{
  const cache = await caches.open(CACHE);
  let done = 0;
  for (const f of FILES) {{
    if (!(await cache.match(f))) {{
      const res = await fetch(f, {{ cache: "reload" }});
      if (!res.ok) throw new Error(f + ": " + res.status);
      await cache.put(f, res);
    }}
    done++;
    if (report && done % 10 === 0) report({{ t: "progress", done, total: FILES.length }});
  }}
}}
async function tell(msg) {{ for (const c of await self.clients.matchAll()) c.postMessage(msg); }}

self.addEventListener("install", e => e.waitUntil(fill(tell).then(() => self.skipWaiting())));
self.addEventListener("activate", e => e.waitUntil((async () => {{
  for (const key of await caches.keys()) if (key.startsWith("spo-") && key !== CACHE) await caches.delete(key);
  await self.clients.claim();
  tell({{ t: "cached" }});
}})()));
self.addEventListener("message", async e => {{
  if (e.data && e.data.t === "status") {{
    const cache = await caches.open(CACHE);
    const missing = (await Promise.all(FILES.map(f => cache.match(f)))).filter(r => !r).length;
    e.source.postMessage(missing ? {{ t: "progress", done: FILES.length - missing, total: FILES.length }} : {{ t: "cached" }});
  }}
}});
// Offline first: the stored copy, the network only for what is missing.
self.addEventListener("fetch", e => {{
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(hit => hit || fetch(e.request)));
}});
""", encoding="utf-8")
print(f"sw.js: {len(files)} Dateien, Version {version}")
